'use client'

import { cn } from '@/lib/utils'
import { useYandexAd } from './useYandexAd'

const BLOCK_ID = 'R-A-19531689-1'
const CONTAINER_ID = 'yandex_rtb_R-A-19531689-1'

type Props = {
	/**
	 * true — колонка-родитель это flex-column с известной высотой (сайдбар
	 * тула, см. ProjectsRightSidebar с boundedHeight). Тогда блок сам
	 * дотягивается flex-grow'ом до низа доступного места вместо угаданного
	 * px — резерв всегда ровно правильный, а не оценка по одному замеру.
	 * false (по умолчанию, сайдбар блога — sticky, без фиксированной
	 * высоты колонки, flex-grow тянуть не от чего) — фиксированный min-h,
	 * снятый с живого рендера блока.
	 */
	fill?: boolean
}

/**
 * Рекламный блок в потоке страницы. Контейнер всегда в DOM, иначе РСЯ некуда
 * рисовать. Высота зарезервирована заранее (см. lib/config/ads.ts) — без
 * резерва блок схлопывался в ноль до заполнения и резко раздвигал вёрстку,
 * когда РСЯ вставляла объявление (так нашли CLS 0,54 на всех 47 страницах
 * тулов на десктопе в GSC, 21.09.2026).
 *
 * При fill=true `min-h-0 overflow-hidden` обязателен вместе с flex-1: без
 * min-h-0 flex-элемент по умолчанию не сжимается меньше высоты своего
 * контента и всё равно раздвинет соседей, если объявление окажется выше
 * отведённого места. С overflow-hidden лишнее просто обрезается визуально —
 * сдвига нет ни при слишком высокой, ни при слишком низкой рекламе.
 *
 * При fill=false (656px) состояние filled на размер не влияет — снятый на
 * /tools/draw-lots замер 288×656 держим одинаковым и до, и после заполнения,
 * иначе усадка контейнера до реального (меньшего) размера объявления сама
 * стала бы сдвигом, только вверх вместо вниз.
 */
export function AdSection({ fill = false }: Props) {
	useYandexAd(BLOCK_ID, CONTAINER_ID)

	return (
		<div
			className={cn(
				'my-6 w-full',
				fill ? 'flex-1 min-h-0 overflow-hidden' : 'min-h-[656px]'
			)}
		>
			<div id={CONTAINER_ID} className='mx-auto w-full' />
		</div>
	)
}
