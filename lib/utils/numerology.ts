/**
 * Нумерология по дате рождения.
 *
 * Считается число жизненного пути — сумма всех цифр даты, свёрнутая до одной.
 * В русскоязычной традиции тот же результат называют и числом судьбы, поэтому
 * тул отвечает на оба запроса: формула одна.
 *
 * Мастер-числа 11, 22 и 33 по канону не сворачиваются дальше — на них свёртка
 * останавливается.
 */

export const MASTER_NUMBERS = [11, 22, 33] as const

/** Сумма цифр числа. */
export function digitSum(value: number): number {
	return Math.abs(Math.trunc(value))
		.toString()
		.split('')
		.reduce((sum, digit) => sum + Number(digit), 0)
}

/**
 * Свёртка до одной цифры с остановкой на мастер-числах.
 *
 * Останавливаемся и на однозначном результате, и на 11/22/33 — иначе 29.11.1993
 * (сумма 11) превратилась бы в двойку и потеряла бы ровно то, ради чего
 * мастер-числа в этой системе выделены.
 */
export function reduceNumber(value: number): number {
	let current = Math.abs(Math.trunc(value))

	while (current > 9 && !MASTER_NUMBERS.includes(current as 11 | 22 | 33)) {
		current = digitSum(current)
	}

	return current
}

/** Число жизненного пути (оно же число судьбы) по дате рождения. */
export function lifePathNumber(
	day: number,
	month: number,
	year: number
): number {
	return reduceNumber(digitSum(day) + digitSum(month) + digitSum(year))
}

/**
 * Число дня рождения — свёрнутое число самого дня, без месяца и года.
 * Считается отдельной характеристикой, поэтому выводится рядом.
 */
export function birthdayNumber(day: number): number {
	return reduceNumber(day)
}

