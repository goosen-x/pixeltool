/** Порядок символов не меняем на уровне глифов — просто разворачиваем строку. */
export function reverseText(text: string): string {
	return [...text].reverse().join('')
}

/**
 * Юникод-глифы, которые визуально выглядят как соответствующая буква/цифра
 * «вверх ногами». Классическая таблица, общая для всех «upside down text»
 * генераторов — не наша выдумка. Кириллица сюда не входит: у большинства
 * кириллических букв просто нет перевёрнутого юникод-аналога.
 */
const FLIP_MAP: Record<string, string> = {
	a: 'ɐ',
	b: 'q',
	c: 'ɔ',
	d: 'p',
	e: 'ǝ',
	f: 'ɟ',
	g: 'ƃ',
	h: 'ɥ',
	i: 'ᴉ',
	j: 'ɾ',
	k: 'ʞ',
	l: 'l',
	m: 'ɯ',
	n: 'u',
	o: 'o',
	p: 'd',
	q: 'b',
	r: 'ɹ',
	s: 's',
	t: 'ʇ',
	u: 'n',
	v: 'ʌ',
	w: 'ʍ',
	x: 'x',
	y: 'ʎ',
	z: 'z',
	'0': '0',
	'1': 'Ɩ',
	'2': 'ᄅ',
	'3': 'Ɛ',
	'4': 'ㄣ',
	'5': 'ϛ',
	'6': '9',
	'7': 'ㄥ',
	'8': '8',
	'9': '6',
	'.': '˙',
	',': "'",
	"'": ',',
	'"': '„',
	'!': '¡',
	'?': '¿',
	'(': ')',
	')': '(',
	'[': ']',
	']': '[',
	'{': '}',
	'}': '{',
	'<': '>',
	'>': '<',
	'&': '⅋',
	_: '‾',
	';': '؛'
}

export function flipUpsideDown(text: string): string {
	const flipped = [...text.toLowerCase()].map(char => FLIP_MAP[char] ?? char)
	return flipped.reverse().join('')
}
