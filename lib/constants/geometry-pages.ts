export function getGeometryPage(
	kind: 'area' | 'volume',
	slug: string
): GeometryPage | undefined {
	return GEOMETRY_PAGES.find(page => page.kind === kind && page.slug === slug)
}

export function geometryPagesByKind(kind: 'area' | 'volume'): GeometryPage[] {
	return GEOMETRY_PAGES.filter(page => page.kind === kind)
}
