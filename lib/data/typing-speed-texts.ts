/**
 * Тексты-доноры для теста скорости печати. Разная длина и лексика —
 * каждый заход даёт новый текст, а не заученный набор символов.
 */
export const TYPING_SPEED_TEXTS: string[] = [
	'Скорость печати измеряется в знаках или словах в минуту. Чем чаще вы печатаете вслепую, не глядя на клавиатуру, тем быстрее растёт результат и тем меньше опечаток остаётся в тексте.',
	'Хорошая осанка и правильное положение пальцев на клавиатуре важнее, чем кажется на первый взгляд. Указательные пальцы держат клавиши Ф и Ы, остальные пальцы расходятся по соседним рядам.',
	'Слепой десятипальцевый метод печати осваивается за несколько недель регулярной практики. Сначала скорость падает, потому что пальцы привыкают к новым движениям, а затем быстро растёт.',
	'Опечатки чаще всего появляются не от незнания букв, а от спешки и потери внимания к экрану. Ровный темп без рывков почти всегда даёт больше точных символов, чем быстрый рваный набор.',
	'Регулярная практика печати полезна не только программистам и копирайтерам. Быстрый и точный набор текста экономит время в переписке, заметках и любой другой повседневной работе за компьютером.',
	'Клавиатурный тренажёр обычно показывает три главных числа: скорость в знаках в минуту, точность в процентах и количество ошибок. Все три вместе дают более честную картину, чем скорость сама по себе.'
]

export function randomTypingText(exclude?: string): string {
	const pool =
		TYPING_SPEED_TEXTS.length > 1
			? TYPING_SPEED_TEXTS.filter(text => text !== exclude)
			: TYPING_SPEED_TEXTS
	return pool[Math.floor(Math.random() * pool.length)]
}
