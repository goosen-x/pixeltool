import type { Metadata } from 'next'

/**
 * Мета-роботс для внутренних страниц (/dev/*).
 *
 * Держим одной константой, чтобы новая внутренняя страница не уехала в индекс
 * из-за забытого блока: раньше он копировался в каждую страницу руками.
 * Дублируется тремя способами намеренно — этот мета-тег, Disallow в
 * app/robots.ts и заголовок X-Robots-Tag в next.config.mjs. Disallow в
 * robots.txt сам по себе от индексации не спасает: закрытую в нём страницу
 * поисковик всё равно может показать в выдаче по внешним ссылкам, зато из-за
 * запрета обхода он не увидит мета-тег. Заголовок закрывает и то, что мета-тег
 * не покрывает в принципе, — не-HTML ответы.
 */
export const NOINDEX: Metadata['robots'] = {
	index: false,
	follow: false,
	nocache: true,
	googleBot: { index: false, follow: false }
}
